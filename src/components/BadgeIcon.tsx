interface Run {
  x: number;
  y: number;
  w: number;
  accent: boolean;
}

const RUNS = Object.fromEntries(
  Object.entries(ICONS).map(([id, grid]) => {
    const runs: Run[] = [];
    grid.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        const ch = row[x];
        if (ch === '#' || ch === '+') {
          let e = x;
          while (e < row.length && row[e] === ch) e++;
          runs.push({ x, y, w: e - x, accent: ch === '+' });
          x = e;
        } else x++;
      }
    });
    return [id, runs];
  }),
) as Record<BadgeId, Run[]>;

/** Earned badges are black with lime details; locked ones turn grey but stay sharp. */
function BadgeIconBase({ id, earned, size = 32 }: { id: BadgeId; earned: boolean; size?: number }) {
  const px = Math.max(1, Math.round(size / 16));
  const main = earned ? colors.ink : '#B9B9B2';
  const accent = earned ? colors.lime : '#DCDCD5';
  return (
    <View
      importantForAccessibility="no-hide-descendants"
      accessibilityElementsHidden
      style={{ width: 16 * px, height: 16 * px }}
    >
      {RUNS[id].map((r, i) => (
        <View
          key={i}
          style={{
            position: 'absolute',
            left: r.x * px,
            top: r.y * px,
            width: r.w * px,
            height: px,
            backgroundColor: r.accent ? accent : main,
          }}
        />
      ))}
    </View>
  );
}

export const BadgeIcon = memo(BadgeIconBase);
